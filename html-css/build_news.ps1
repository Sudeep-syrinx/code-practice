function Write-Lines($filename, $lines) {
    Remove-Item $filename -ErrorAction SilentlyContinue
    foreach ($line in $lines) {
        Add-Content -Path $filename -Value $line -Encoding UTF8
    }
    $count = (Get-Content $filename | Measure-Object -Line).Lines
    Write-Host "  ✅ $filename : $count lines" -ForegroundColor Green
}

